"""Source-owned value contracts.

The contracts in this module are deliberately independent of any engine
implementation. A reader owns the resolved selection and candidate returned
for one invocation; runtime is a detached projection of that same evidence.
"""

from __future__ import annotations

import copy
from dataclasses import dataclass
from datetime import datetime
from enum import Enum
from typing import TYPE_CHECKING, Any, Generic, Mapping, TypeVar

if TYPE_CHECKING:
    from datacoolie.sources.runtime import SourceRuntimeInfo
    from datacoolie.watermark.contracts import WatermarkCandidate


DF = TypeVar("DF")


class SourceReadMode(str, Enum):
    """Finite source selection modes."""

    FULL = "full"
    INCREMENTAL = "incremental"
    RANGE = "range"


class SourceReadUpperOrigin(str, Enum):
    """Whether a selection ceiling was authored or generated by the source."""

    NONE = "none"
    EXPLICIT = "explicit"
    GENERATED = "generated"


_LOWER_OPERATORS = frozenset({">", ">="})
_UPPER_OPERATORS = frozenset({"<", "<="})


@dataclass(frozen=True, slots=True)
class SourceReadRange:
    """Exact source-owned range for one bounded read."""

    column: str
    start: Any
    end: Any
    lower_operator: str = ">="
    upper_operator: str = "<"

    def __post_init__(self) -> None:
        if not isinstance(self.column, str) or not self.column.strip():
            raise ValueError("SourceReadRange.column must be a non-empty string")
        if self.start is None or self.end is None:
            raise ValueError("SourceReadRange.start and end must not be None")
        if self.lower_operator not in _LOWER_OPERATORS:
            raise ValueError(
                f"Unsupported SourceReadRange.lower_operator: {self.lower_operator!r}"
            )
        if self.upper_operator not in _UPPER_OPERATORS:
            raise ValueError(
                f"Unsupported SourceReadRange.upper_operator: {self.upper_operator!r}"
            )


@dataclass(frozen=True, slots=True)
class SourceReadRequest:
    """Caller-owned input for exactly one source read."""

    reference_time: datetime
    watermark_start: dict[str, Any] | None = None
    watermark_end: dict[str, Any] | None = None
    watermark_start_operator: str | None = None
    watermark_end_operator: str | None = None
    read_range: SourceReadRange | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.reference_time, datetime):
            raise TypeError("SourceReadRequest.reference_time must be a datetime")
        for name in ("watermark_start", "watermark_end"):
            value = getattr(self, name)
            if value is not None:
                if not isinstance(value, Mapping):
                    raise TypeError(f"SourceReadRequest.{name} must be a mapping or None")
                if any(not isinstance(key, str) for key in value):
                    raise TypeError(f"SourceReadRequest.{name} keys must be strings")
                object.__setattr__(self, name, copy.deepcopy(dict(value)))
        if self.watermark_start_operator is not None and self.watermark_start_operator not in _LOWER_OPERATORS:
            raise ValueError(
                "SourceReadRequest.watermark_start_operator must be '>' or '>='"
            )
        if self.watermark_end_operator is not None and self.watermark_end_operator not in _UPPER_OPERATORS:
            raise ValueError(
                "SourceReadRequest.watermark_end_operator must be '<' or '<='"
            )
        if self.read_range is not None and not isinstance(self.read_range, SourceReadRange):
            raise TypeError("SourceReadRequest.read_range must be a SourceReadRange or None")
        if self.read_range is not None and (
            self.watermark_start is not None
            or self.watermark_end is not None
            or self.watermark_start_operator is not None
            or self.watermark_end_operator is not None
        ):
            raise ValueError(
                "SourceReadRequest.read_range cannot be combined with explicit "
                "watermark bounds or operators"
            )


@dataclass(frozen=True, slots=True)
class SourceReadSelection:
    """Source-resolved predicate used by one read."""

    mode: SourceReadMode = SourceReadMode.FULL
    lower: dict[str, Any] | None = None
    upper: dict[str, Any] | None = None
    lower_operator: str = ">"
    upper_operator: str = "<"
    combine_operator: str = "OR"
    upper_origin: SourceReadUpperOrigin = SourceReadUpperOrigin.NONE

    def __post_init__(self) -> None:
        object.__setattr__(self, "mode", SourceReadMode(self.mode))
        object.__setattr__(self, "upper_origin", SourceReadUpperOrigin(self.upper_origin))
        if self.lower_operator not in _LOWER_OPERATORS:
            raise ValueError(
                f"Unsupported SourceReadSelection.lower_operator: {self.lower_operator!r}"
            )
        if self.upper_operator not in _UPPER_OPERATORS:
            raise ValueError(
                f"Unsupported SourceReadSelection.upper_operator: {self.upper_operator!r}"
            )
        if self.combine_operator != "OR":
            raise ValueError(
                f"Unsupported SourceReadSelection.combine_operator: {self.combine_operator!r}"
            )
        for name in ("lower", "upper"):
            value = getattr(self, name)
            if value is not None:
                if not isinstance(value, Mapping):
                    raise TypeError(f"SourceReadSelection.{name} must be a mapping or None")
                if any(not isinstance(key, str) for key in value):
                    raise TypeError(f"SourceReadSelection.{name} keys must be strings")
                object.__setattr__(self, name, copy.deepcopy(dict(value)))


@dataclass(frozen=True, slots=True)
class SourceReadResult(Generic[DF]):
    """Frame and source-owned control evidence produced together."""

    frame: DF | None
    rows_read: int
    selection: SourceReadSelection
    candidate: WatermarkCandidate | None = None
    runtime: SourceRuntimeInfo | None = None

    def __post_init__(self) -> None:
        if isinstance(self.rows_read, bool) or not isinstance(self.rows_read, int):
            raise TypeError("SourceReadResult.rows_read must be a non-negative integer")
        if self.rows_read < 0:
            raise ValueError("SourceReadResult.rows_read must be non-negative")
        if self.frame is None and self.rows_read != 0:
            raise ValueError("SourceReadResult.frame=None requires rows_read=0")
        if not isinstance(self.selection, SourceReadSelection):
            raise TypeError("SourceReadResult.selection must be SourceReadSelection")
        if self.candidate is not None:
            from datacoolie.watermark.contracts import WatermarkCandidate

            if not isinstance(self.candidate, WatermarkCandidate):
                raise TypeError("SourceReadResult.candidate must be WatermarkCandidate or None")
